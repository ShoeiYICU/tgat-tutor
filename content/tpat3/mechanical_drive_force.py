def mq(stem, fig, answer, wrong, steps, hints, explain, **kw):
    assert len({answer} | {w for w, _ in wrong}) == 5, f"ตัวเลือกซ้ำกัน: {stem[:40]}"
    return q(stem + "\n\n[[fig1]]", answer, wrong, steps, hints, explain, figures=[fig], **kw)


