VIEW_TH = {"front": "ด้านหน้า", "side": "ด้านข้าง", "top": "ด้านบน"}


def shown(view: str, cells2d, as_seen: bool = False):
    """แปลงภาพฉายดิบเป็นภาพที่วาด: ภาพหน้าและข้างกลับแกน z ให้ชั้นบนอยู่แถวบน

    as_seen=True ใช้เมื่อมีลูกศรบอกทิศมอง ให้ซ้ายขวาตรงกับที่คนยืนตามลูกศรเห็นจริง
    ในภาพไอโซเมตริก +x ชี้ขวาล่าง +y ชี้ซ้ายล่าง มือขวาของผู้มองคือทิศที่หมุนตามเข็ม 90 องศา
    จากทิศที่หันหน้าไป (เมื่อดูบนจอ)
        ลูกศร "front" หันไปขวาบน มือขวาชี้ขวาล่าง = +x จึงไม่ต้องพลิก
        ลูกศร "side" หันไปซ้ายบน มือขวาชี้ขวาบน = -y จึงต้องพลิกแกน y
    """
    if view == "top":
        return S2.normalize(cells2d)
    zmax = max(z for _, z in cells2d)
    if as_seen and view == "side":
        return S2.normalize((-a, zmax - z) for a, z in cells2d)
    return S2.normalize((a, zmax - z) for a, z in cells2d)


def flat_fig(fid, cells2d, cap=""):
    return {"id": fid, "type": "svg", "svg": S2.shape_svg(cells2d), "alt": S2.describe(cells2d), "caption": cap}


def solid_fig(fid, cells, view=None, cap="ทรงที่ประกอบจากลูกบาศก์"):
    alt = S3.describe(cells)
    if view:
        alt += f" · มีลูกศรบอกให้มองจาก{VIEW_TH[view]}"
    return {"id": fid, "type": "svg", "svg": M.iso_view_svg(cells, view), "alt": alt, "caption": cap}


def pick_distinct(answer, candidates, n=4):
    """เลือกตัวลวง n ตัวตามลำดับ โดยทุกตัวต้องไม่เท่ากับคำตอบและไม่เท่ากันเองแม้หมุนหรือพลิก"""
    chosen, keys, whys = [], {M.canon2d(answer)}, set()
    for shape, why in candidates:
        k = M.canon2d(shape)
        if k in keys or why in whys:     # เหตุผลซ้ำกันในข้อเดียวไม่ช่วยให้ผู้เรียนแยกแยะได้
            continue
        keys.add(k)
        whys.add(why)
        chosen.append((shape, why))
        if len(chosen) == n:
            return chosen
    raise AssertionError(f"หาตัวลวงที่ต่างกันจริงได้เพียง {len(chosen)} ตัว")


def near_misses(shape):
    """รูปที่ขาดหรือเกินไปหนึ่งช่อง เรียงแบบคงที่เพื่อให้ได้ผลเหมือนเดิมทุกครั้ง"""
    shape = set(shape)
    out = []

    def r0(c):
        return c[1] + 1
    for c in sorted(shape):
        rest = shape - {c}
        if rest and _connected(rest):
            out.append((S2.normalize(rest),
                        f"ขาดช่องแถวที่ {r0(c)} คอลัมน์ที่ {c[0] + 1} ไป ทั้งที่แนวนั้นมีลูกบาศก์อยู่"))
    for c, r in sorted(shape):
        for d in ((1, 0), (0, 1), (-1, 0), (0, -1)):
            n = (c + d[0], r + d[1])
            if n not in shape:
                out.append((S2.normalize(shape | {n}),
                            "มีช่องเกินมาหนึ่งช่องตรงแนวที่ไม่มีลูกบาศก์ก้อนใดอยู่"
                            if n[1] >= 0 and n[0] >= 0 else
                            "มีช่องยื่นออกไปนอกขอบของทรง ซึ่งไม่มีลูกบาศก์อยู่เลย"))
    return out


def _connected(cells):
    cells = set(cells)
    start = next(iter(cells))
    seen, stack = {start}, [start]
    while stack:
        c, r = stack.pop()
        for d in ((1, 0), (0, 1), (-1, 0), (0, -1)):
            n = (c + d[0], r + d[1])
            if n in cells and n not in seen:
                seen.add(n)
                stack.append(n)
    return len(seen) == len(cells)


def view_item(solid, view, stem, steps, hints, explain, arrow=True, extra=(), **kw):
    """โจทย์เลือกภาพฉายที่ถูก · ตัวลวงสร้างจากภาพด้านอื่น ภาพชั้นล่าง และภาพที่ขาดเกินหนึ่งช่อง"""
    # ก้อนที่ถูกบังมิดและไม่ได้รองรับก้อนอื่น ผู้ทำมองไม่เห็นจากรูป ถ้ามันเปลี่ยนคำตอบ โจทย์จะตอบไม่ได้
    assert M.view_determinable(solid, view), f"ภาพ{VIEW_TH[view]}ขึ้นกับก้อนที่มองไม่เห็นในรูป: {stem[:30]}"
    v = M.raw_views(solid)
    ans = shown(view, v[view], arrow)
    others = [o for o in ("front", "side", "top") if o != view]
    cands = [(shown(o, v[o], arrow), f"เป็นภาพเมื่อมองจาก{VIEW_TH[o]} ไม่ใช่จาก{VIEW_TH[view]}") for o in others]
    cands += list(extra)
    if view != "top":
        low = [c for c in solid if c[2] == 0]
        cands.append((shown(view, M.raw_views(low)[view], arrow), "เห็นเฉพาะชั้นล่าง ลืมก้อนที่ซ้อนอยู่ข้างบน"))
    cands += near_misses(ans)
    wrong = pick_distinct(ans, cands)
    figs = [solid_fig("fig1", solid, view if arrow else None)]
    labels = []
    for i, shape in enumerate([ans] + [w for w, _ in wrong]):
        figs.append(flat_fig(f"fig{i + 2}", shape))
        labels.append(f"[[fig{i + 2}]]")
    return q(stem + "\n\n[[fig1]]", labels[0], [(labels[i + 1], why) for i, (_, why) in enumerate(wrong)],
             steps, hints, explain, figures=figs, **kw)


