tk = M.Tackle(2, 600)
assert tk.supporting() == 4

chain = M.Drive([("A", 20), ("B", 40), ("C", 20), ("D", 30)], ["mesh", "cross", "belt"])
kinds = {f"{chain.wheels[i][0]} กับ {chain.wheels[i + 1][0]}": k for i, k in enumerate(chain.links)}
assert kinds["B กับ C"] == "cross"

lv = M.Lever(5, 2, [(0, 30, "ก"), (5, 20, "ข")])
arm_b = 5 - lv.pivot
assert arm_b == 3

fz = M.Forces([("ก", 8, 0), ("ข", 0, 3), ("ค", -3, -4)])
mags = {n: M.Forces([(n, x, y)]).magnitude() for n, x, y in fz.v}
assert max(mags, key=mags.get) == "ก" and sorted(mags.values()) == [3, 5, 8]

sh = M.Drive([("A", 10), ("B", 40), ("C", 20), ("D", 10)], ["mesh", "shaft", "belt"])
sp = sh.speed()
same_as_b = [sh.wheels[i][0] for i in range(4) if i != 1 and sp[i] == sp[1]]
assert same_as_b == ["C"], same_as_b

