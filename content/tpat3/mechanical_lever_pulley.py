# --- ข้อ 1: คานเอียงทางไหน (ซ้ายหนักกว่า)
lv1 = M.Lever(4, 2, [(0, 30, "ก"), (3, 30, "ข")])
assert lv1.tips() == "ซ้ายลง" and lv1.moment("left") == 60 and lv1.moment("right") == 30

# --- ข้อ 2: กระดานหก หาระยะที่ทำให้สมดุล
# รูปแสดงเฉพาะฝั่งเด็ก เพราะระยะของผู้ใหญ่คือสิ่งที่โจทย์ถาม
lv2 = M.Lever(5, 2.5, [(1, 300, "เด็ก")])
assert M.Lever(5, 2.5, [(1, 300, "เด็ก"), (3.5, 450, "ผู้ใหญ่")]).balanced(), "กระดานหกต้องสมดุลที่ 1 เมตร"

# --- ข้อ 3: ชะแลง หาแรงที่ต้องออก
lv3 = M.Lever(1.4, 0.2, [(0, 600, "ของ")])
f3 = lv3.solve_force(1.4)
assert f3 == 100, f"ชะแลงควรใช้แรง 100 N แต่ได้ {f3}"

# --- ข้อ 4: คานสามน้ำหนัก
lv4 = M.Lever(6, 3, [(0, 40, "ก"), (1, 20, "ข"), (6, 60, "ค")])
assert lv4.tips() == "ขวาลง" and lv4.moment("left") == 160 and lv4.moment("right") == 180

# --- ข้อ 5: รถเข็นล้อเดียว (คานอันดับสอง จุดหมุนคือล้อ แรงยกอยู่ด้านเดียวกับของ)
lv5 = M.Lever(1.2, 0, [(0.4, 900, "ของ")])
f5 = lv5.solve_force(1.2, up=True)
assert f5 == 300, f"รถเข็นควรใช้แรง 300 N แต่ได้ {f5}"
# รูปในโจทย์ต้องไม่แสดงแรงที่มือ เพราะนั่นคือสิ่งที่ถาม จึงตรวจสมดุลแยกไว้ต่างหาก
assert M.Lever(1.2, 0, [(0.4, 900, "ของ"), (1.2, -f5, "มือ")]).balanced(), "ใส่แรงยกแล้วต้องสมดุล"

# --- ข้อ 6: เติมน้ำหนักให้สมดุล
