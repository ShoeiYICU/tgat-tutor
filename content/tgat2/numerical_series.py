def series_lesson(tid, title, sub, rule_md, how, example_stem, example_steps, ans, pit, prereq, nxt, check_q, check_choices, check_i, check_exp):
    return lesson(tid, title, sub,
        objectives=["มองหารูปแบบของอนุกรมแบบนี้ได้ภายใน 20 วินาที", "หาพจน์ถัดไปหรือพจน์ที่หายไปได้", "แยกอนุกรมแบบนี้ออกจากแบบที่หน้าตาคล้ายกัน"],
        minutes=20, prereq=prereq, nxt=nxt,
        blocks=[
            hook("ขั้นแรกของอนุกรมทุกข้อคือ **เขียนผลต่างลงไป** ถ้าผลต่างไม่คงที่ บทนี้คือหนึ่งในรูปแบบที่ต้องลองถัดไป"),
            concept("รูปแบบของอนุกรม", rule_md),
            technique("วิธีตรวจ", "เมื่อผลต่างชั้นแรกไม่คงที่", "ถ้าผลต่างชั้นแรกคงที่ ใช้วิธีอนุกรมผลต่างคงที่ได้เลย", how, tip="เขียนผลต่างก่อนเสมอ"),
            example("ตัวอย่างที่ 1", example_stem, example_steps, ans),
            pitfall(*pit),
            summary("เขียนผลต่างก่อนทุกครั้ง", "ถ้าผลต่างไม่คงที่ ดูรูปแบบของผลต่างต่อ", "ตรวจคำตอบด้วยการเดินรูปแบบซ้ำอีกครั้ง"),
            check(check_q, check_choices, check_i, check_exp),
        ],
        patterns=["หาพจน์ถัดไป", "หาพจน์ที่หายไปตรงกลาง"],
        sources=SRC)


