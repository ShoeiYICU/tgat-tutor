LAB = "กขคงจฉ"
ARROW = {"ขึ้น": "up", "ขวา": "right", "ลง": "down", "ซ้าย": "left"}


def solved(net):
    cells = CN.NETS[net]
    r = CN.solve_net(cells)
    assert r["valid"], f"{net}: {r['error']}"
    return cells, r


def opposite(net, face):
    _, r = solved(net)
    for a, b in r["pairs"]:
        if a == face:
            return b
        if b == face:
            return a
    raise AssertionError(f"{net}: ไม่พบหน้า {face}")


def neighbours(net, face):
    """สี่หน้าที่ติดกับ face หลังพับ เรียงตามลำดับตัวอักษร ก ข ค ง จ ฉ"""
    return [x for x in LAB if x != face and x != opposite(net, face)]


def points_to(net, face, direction):
    """สัญลักษณ์บนหน้า face ที่ชี้ไปทาง direction บนแผ่นคลี่ พับแล้วชี้ไปทางหน้าใด"""
    _, r = solved(net)
    n, rt, up = r["frames"][face]
    vec = {"up": up, "down": tuple(-v for v in up),
           "right": rt, "left": tuple(-v for v in rt)}[ARROW[direction]]
    for lab, nv in r["normals"].items():
        if tuple(nv) == tuple(vec):
            return lab
    raise AssertionError(f"{net}: หาหน้าที่ตรงกับทิศไม่ได้")


def net_fig(net, marks=()):
    """วาดแผ่นคลี่ · marks = [(face, direction)] วาดลูกศรทับบนหน้านั้น"""
    cells = CN.NETS[net]
    svg = CN.net_svg(cells)
    pos = {lab: (c, r) for c, r, lab in cells}
    deg = {"ขึ้น": 0, "ขวา": 90, "ลง": 180, "ซ้าย": 270}
    extra = []
    for face, d in marks:
        c, r = pos[face]
        x, y = CN.ORIGIN + c * CN.CELL, CN.ORIGIN + r * CN.CELL
        cx, cy = x + CN.CELL // 2, y + CN.CELL // 2
        # ย้ายตัวอักษรของหน้าที่มีลูกศรไปไว้มุมซ้ายบนของช่อง ไม่ให้ลูกศรทับ
        old = f'<text x="{cx}" y="{y + 29}">{face}</text>'
        assert old in svg, f"หาตัวอักษรของหน้า {face} ในภาพไม่เจอ"
        svg = svg.replace(old, f'<text x="{x + 10}" y="{y + 16}" font-size="13">{face}</text>')
        extra.append(
            f'<g transform="rotate({deg[d]} {cx} {cy})" stroke="var(--accent, #3b5bdb)" '
            f'stroke-width="3" fill="var(--accent, #3b5bdb)">'
            f'<line x1="{cx}" y1="{cy + 12}" x2="{cx}" y2="{cy - 5}"/>'
            f'<polygon points="{cx},{cy - 14} {cx + 6},{cy - 3} {cx - 6},{cy - 3}" stroke-width="1"/></g>')
    if extra:
        svg = svg.replace("</svg>", "".join(extra) + "</svg>")
    alt = CN.describe(cells)
    if marks:
        alt += " · " + " · ".join(f"หน้า {f} มีลูกศรชี้{d}" for f, d in marks)
    return {"id": "fig1", "type": "svg", "svg": svg, "alt": alt, "caption": "แผ่นคลี่ลูกบาศก์"}


def net_q(stem, net, answer, wrong, steps, hints, explain, marks=(), **kw):
    assert len({answer} | {w for w, _ in wrong}) == 5, f"ตัวเลือกซ้ำ: {stem}"
    return q(stem + "\n\n[[fig1]]", answer, wrong, steps, hints, explain,
             figures=[net_fig(net, marks)], **kw)


