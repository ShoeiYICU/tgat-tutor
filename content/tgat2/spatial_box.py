def arrow_item(net, face, d, stem, steps, hints, explain, **kw):
    ans = points_to(net, face, d)
    opp = opposite(net, face)
    wrong = [(face, "ลูกศรวางอยู่บนหน้านี้เอง จึงชี้ไปหาตัวเองไม่ได้"),
             (opp, f"หน้านี้เป็นหน้าตรงข้ามของ {face} อยู่คนละฝั่งของกล่อง ลูกศรชี้ไปไม่ถึง")]
    wrong += [(x, "หน้านี้ติดกับหน้าที่มีลูกศร แต่อยู่คนละด้านกับทิศที่ลูกศรชี้")
              for x in neighbours(net, face) if x != ans][:2]
    return net_q(stem, net, ans, wrong, steps, hints, explain, marks=[(face, d)], **kw)


def two_arrow_item(net, f1, d1, f2, d2, stem, steps, hints, explain, **kw):
    a1, a2 = points_to(net, f1, d1), points_to(net, f2, d2)
    ans = f"{a1} และ {a2}"
    cand = [(f"{a2} และ {a1}", "สลับลำดับของสองลูกศร"),
            (f"{opposite(net, f1)} และ {a2}", f"ลูกศรแรกตอบเป็นหน้าตรงข้ามของ {f1} ซึ่งลูกศรชี้ไปไม่ถึง"),
            (f"{a1} และ {opposite(net, f2)}", f"ลูกศรที่สองตอบเป็นหน้าตรงข้ามของ {f2}"),
            (f"{f1} และ {f2}", "ตอบหน้าที่ลูกศรวางอยู่ แทนหน้าที่ลูกศรชี้ไป"),
            (f"{a1} และ {f2}", "ลูกศรที่สองตอบเป็นหน้าที่ตัวมันเองวางอยู่")]
    wrong, seen = [], {ans}
    for text, why in cand:
        if text not in seen and len(wrong) < 4:
            seen.add(text)
            wrong.append((text, why))
    assert len(wrong) == 4, stem
    return net_q(stem, net, ans, wrong, steps, hints, explain, marks=[(f1, d1), (f2, d2)], **kw)


