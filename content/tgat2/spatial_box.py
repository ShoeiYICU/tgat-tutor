def opp_item(net, face, stem, steps, hints, explain, **kw):
    ans = opposite(net, face)
    _, r = solved(net)
    wrong = []
    for x in neighbours(net, face):
        if frozenset((x, face)) in r["touching"]:
            why = f"หน้า {x} อยู่ชิดกับหน้า {face} บนแผ่นคลี่ พับแล้วจึงกลายเป็นหน้าที่ติดกัน ไม่ใช่หน้าตรงข้าม"
        else:
            why = (f"หน้า {x} ไม่ได้อยู่แนวเดียวกับหน้า {face} แบบเว้นหนึ่งช่อง "
                   f"เมื่อพับแล้วจึงติดกับหน้า {face} ไม่ใช่อยู่ตรงข้าม")
        wrong.append((x, why))
    return net_q(stem, net, ans, wrong, steps, hints, explain, **kw)


