def arrange(names, slots, rules):
    """จัดแต่ละชื่อลงช่องไม่ซ้ำกัน คืน list ของ dict ชื่อ -> ช่อง"""
    out = []
    for perm in permutations(slots, len(names)):
        d = dict(zip(names, perm))
        if all(r(d) for r in rules):
            out.append(d)
    return out


def teams(names, sizes, rules):
    """แบ่งคนลงกลุ่มตามขนาด sizes = {กลุ่ม: จำนวนคน}"""
    out = []
    for combo in product(list(sizes), repeat=len(names)):
        if Counter(combo) != Counter(sizes):
            continue
        d = dict(zip(names, combo))
        if all(r(d) for r in rules):
            out.append(d)
    return out


def who(sols, f, stem, wrong, steps, hints, explain, **kw):
    """คำถามที่คำตอบต้องมีค่าเดียวในทุกกรณี"""
    assert sols, stem
    vals = {f(s) for s in sols}
    assert len(vals) == 1, f"คำตอบไม่เดียว: {vals} · {stem}"
    ans = vals.pop()
    assert ans not in [w for w, _ in wrong], stem
    return q(stem, ans, wrong, steps, hints, explain, **kw)


def claim(sols, mode, stem, ans, wrong, steps, hints, explain, **kw):
    """ans = (ข้อความ, ฟังก์ชัน) · wrong = [(ข้อความ, ฟังก์ชัน, เหตุผล)]
    mode: must = ต้องเป็นจริง · can = เป็นไปได้ · cannot = เป็นไปไม่ได้"""
    assert sols, stem
    t = lambda f: all(f(s) for s in sols)
    c = lambda f: any(f(s) for s in sols)
    if mode == "must":
        assert t(ans[1]), stem
        assert all(not t(w[1]) for w in wrong), stem
    elif mode == "can":
        assert c(ans[1]), stem
        assert all(not c(w[1]) for w in wrong), stem
    elif mode == "cannot":
        assert not c(ans[1]), stem
        assert all(c(w[1]) for w in wrong), stem
    return q(stem, ans[0], [(w[0], w[2]) for w in wrong], steps, hints, explain, **kw)


