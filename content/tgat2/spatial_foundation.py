def pos(c, r):
    return f"แถวที่ {r + 1} จากบน คอลัมน์ที่ {c + 1} จากซ้าย"


def fig(fid, cells, marked=None, cap=""):
    return {"id": fid, "type": "svg", "svg": S2.shape_svg(cells, marked=marked),
            "alt": S2.describe(cells) + (f" · ช่องที่ทำเครื่องหมายอยู่{pos(*marked)}" if marked else ""),
            "caption": cap}


def apply_tf(cells, marked, tf):
    """หมุนหรือสะท้อนทั้งรูปพร้อมช่องที่ทำเครื่องหมาย คืน (รูปใหม่, ช่องใหม่)"""
    maps = {"rot90": lambda c, r: (-r, c), "rot180": lambda c, r: (-c, -r),
            "rot270": lambda c, r: (r, -c), "flip": lambda c, r: (-c, r)}
    f = maps[tf]
    raw = [f(c, r) for c, r in cells]
    mc, mr = min(c for c, _ in raw), min(r for _, r in raw)
    new = frozenset((c - mc, r - mr) for c, r in raw)
    m = f(*marked)
    return new, (m[0] - mc, m[1] - mr)


def grid_item(cells, marked, tf, stem, steps, hints, explain, diff=2, sec=45):
    """โจทย์ตำแหน่งช่อง: คำตอบคำนวณจากรูปจริง ตัวลวงคือความผิดพลาดที่พบบ่อย"""
    cells = S2.normalize(cells)
    new, m2 = apply_tf(cells, marked, tf) if tf else (cells, marked)
    w, h = S2.size_of(new)
    ans = pos(*m2)
    shift = lambda v, n: v - 1 if v > 0 else v + 1        # เลื่อนหนึ่งช่องโดยไม่หลุดออกนอกรูป
    cand = [
        (pos(m2[1], m2[0]), "สลับแถวกับคอลัมน์"),
        (pos(w - 1 - m2[0], m2[1]), "นับคอลัมน์จากขวาแทนจากซ้าย"),
        (pos(m2[0], h - 1 - m2[1]), "นับแถวจากล่างแทนจากบน"),
        (pos(*marked), "ตอบตำแหน่งเดิมโดยไม่ได้เปลี่ยนรูป"),
        (pos(shift(m2[0], w), m2[1]), "นับคอลัมน์คลาดไปหนึ่งช่อง"),
        (pos(m2[0], shift(m2[1], h)), "นับแถวคลาดไปหนึ่งช่อง"),
        (pos(w - 1 - m2[0], h - 1 - m2[1]), "นับทั้งแถวและคอลัมน์จากอีกด้าน"),
    ]
    wrong, seen = [], {ans}
    for text, why in cand:
        if text not in seen and len(wrong) < 4:
            seen.add(text)
            wrong.append((text, why))
    assert len(wrong) == 4, f"ตัวลวงไม่พอ: {stem}"
    return q(stem + "\n\n[[fig1]]", ans, wrong, steps, hints, explain,
             diff=diff, sec=sec, figures=[fig("fig1", cells, marked, "รูปต้นแบบ · ช่องที่ทำเครื่องหมายคือช่องที่มีเส้นประ")])


