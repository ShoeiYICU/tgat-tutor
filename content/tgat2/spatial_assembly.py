def shift(cells, dc, dr):
    return frozenset((c + dc, r + dr) for c, r in cells)


def forms(target, a, b, rotate):
    """วางชิ้น a และ b ให้เต็ม target พอดีได้ไหม (ไม่ซ้อนทับ ไม่เกินขอบ)"""
    target = S2.normalize(target)
    if len(a) + len(b) != len(target):
        return False
    w, h = S2.size_of(target)
    a_forms = set(S2.rotations(a)) if rotate else {S2.normalize(a)}
    b_forms = set(S2.rotations(b)) if rotate else {S2.normalize(b)}
    for av in a_forms:
        aw, ah = S2.size_of(av)
        for dc in range(w - aw + 1):
            for dr in range(h - ah + 1):
                placed = shift(av, dc, dr)
                if not placed <= target:
                    continue
                rest = S2.normalize(target - placed)
                if rest in b_forms:
                    return True
    return False


def connected(cells):
    cells = set(cells)
    seen = {next(iter(cells))}
    stack = list(seen)
    while stack:
        c, r = stack.pop()
        for nxt in ((c + 1, r), (c - 1, r), (c, r + 1), (c, r - 1)):
            if nxt in cells and nxt not in seen:
                seen.add(nxt)
                stack.append(nxt)
    return len(seen) == len(cells)


def decoys(target, a, b, rotate, want=4):
    """สร้างตัวลวง: ย้ายช่องหนึ่งช่องของคำตอบไปติดที่อื่น แล้วเก็บเฉพาะรูปที่ประกอบไม่ได้จริง"""
    target = S2.normalize(target)
    out, seen = [], {target}
    for drop in sorted(target):
        rest = target - {drop}
        if not rest or not connected(rest):
            continue
        spots = sorted({(c + dc, r + dr) for c, r in rest
                        for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1))} - rest)
        for spot in spots:
            cand = S2.normalize(rest | {spot})
            if cand in seen or len(cand) != len(target):
                continue
            seen.add(cand)
            if forms(cand, a, b, rotate):      # ประกอบได้ จึงใช้เป็นตัวลวงไม่ได้
                continue
            out.append(cand)
            if len(out) == want:
                return out
    raise AssertionError("สร้างตัวลวงไม่พอ")


def joined(a, b, rotate, pick=0):
    """สร้างรูปเป้าหมายด้วยการวางชิ้น b ต่อกับชิ้น a จริง ๆ ทุกตำแหน่งที่เป็นไปได้

    คืนรูปลำดับที่ pick (เรียงแบบคงที่ จึง build ซ้ำได้ผลเดิม)
    ใช้แทนการกะตำแหน่งด้วยมือ ซึ่งพลาดเป็นรูปที่ซ้อนทับกันได้ง่าย
    """
    a = S2.normalize(a)
    b_forms = sorted(set(S2.rotations(b)) if rotate else {S2.normalize(b)}, key=lambda s: sorted(s))
    w, h = S2.size_of(a)
    out, seen = [], set()
    for bv in b_forms:
        bw, bh = S2.size_of(bv)
        for dc in range(-bw, w + 1):
            for dr in range(-bh, h + 1):
                pb = shift(bv, dc, dr)
                if pb & a:
                    continue
                u = S2.normalize(a | pb)
                if len(u) != len(a) + len(b) or not connected(u) or u in seen:
                    continue
                seen.add(u)
                out.append(u)
    out.sort(key=lambda s: (S2.size_of(s), sorted(s)))
    assert out, "วางชิ้นส่วนสองชิ้นนี้ต่อกันไม่ได้เลย"
    return out[pick % len(out)]


def fig2(fid, cells, cap=""):
    return {"id": fid, "type": "svg", "svg": S2.shape_svg(cells), "alt": S2.describe(cells), "caption": cap}


def _parts(svg):
    """แยกขนาดกับเนื้อในของ SVG ที่ shape_svg สร้าง เพื่อนำไปวางต่อกันในภาพเดียว"""
    head, body = svg.split(">", 1)
    w, h = (float(v) for v in head.split('viewBox="0 0 ', 1)[1].split('"', 1)[0].split())
    return w, h, body.rsplit("</svg>", 1)[0]


def pieces_fig(a, b):
    """วาดชิ้นส่วนสองชิ้นไว้ในภาพเดียว เรียงซ้ายขวา พร้อมหมายเลขกำกับ"""
    wa, ha, ba = _parts(S2.shape_svg(a))
    wb, hb, bb = _parts(S2.shape_svg(b))
    gap, top = 34, 20
    w, h = wa + gap + wb, max(ha, hb) + top
    label = ('<g fill="currentColor" font-size="13" font-family="system-ui, sans-serif" text-anchor="middle">'
             f'<text x="{wa / 2:.0f}" y="14">ชิ้นที่ 1</text>'
             f'<text x="{wa + gap + wb / 2:.0f}" y="14">ชิ้นที่ 2</text></g>')
    return {"id": "fig1", "type": "svg", "caption": "ชิ้นส่วนที่ต้องนำมาต่อกัน",
            "alt": f"ชิ้นที่ 1: {S2.describe(a)} · ชิ้นที่ 2: {S2.describe(b)}",
            "svg": (f'<svg viewBox="0 0 {w:.0f} {h:.0f}" xmlns="http://www.w3.org/2000/svg" role="img">{label}'
                    f'<g transform="translate(0 {top})">{ba}</g>'
                    f'<g transform="translate({wa + gap:.0f} {top})">{bb}</g></svg>')}


def placement(target, a, b, rotate):
    """คืนช่องที่ชิ้น a ครอบครองในคำตอบ (วิธีวางแรกที่เจอ) ใช้เขียนเฉลยให้ตรงกับรูปจริง"""
    target = S2.normalize(target)
    w, h = S2.size_of(target)
    a_forms = sorted(set(S2.rotations(a)) if rotate else {S2.normalize(a)}, key=lambda s: sorted(s))
    for av in a_forms:
        aw, ah = S2.size_of(av)
        for dc in range(w - aw + 1):
            for dr in range(h - ah + 1):
                placed = shift(av, dc, dr)
                if placed <= target and S2.normalize(target - placed) in (
                        set(S2.rotations(b)) if rotate else {S2.normalize(b)}):
                    return placed
    raise AssertionError("หาวิธีวางไม่ได้")


def where(cells):
    return " ".join(f"(แถว {r + 1}, คอลัมน์ {c + 1})" for c, r in sorted(cells, key=lambda t: (t[1], t[0])))


def why_not_formable(cand, a, b, rotate):
    """อธิบายเฉพาะรูปนั้นว่าทำไมประกอบไม่ได้ โดยบอกว่าวางชิ้นที่ 1 แล้วช่องที่เหลือกลายเป็นรูปอะไร"""
    cand = S2.normalize(cand)
    w, h = S2.size_of(cand)
    a_forms = sorted(set(S2.rotations(a)) if rotate else {S2.normalize(a)}, key=lambda s: sorted(s))
    for av in a_forms:
        aw, ah = S2.size_of(av)
        for dc in range(w - aw + 1):
            for dr in range(h - ah + 1):
                placed = shift(av, dc, dr)
                if placed <= cand:
                    rest = S2.normalize(cand - placed)
                    return (f"วางชิ้นที่ 1 ลงในรูปนี้ได้ แต่ช่องที่เหลือกลายเป็น{S2.describe(rest)} "
                            "ซึ่งไม่ใช่รูปของชิ้นที่ 2 และวางตำแหน่งอื่นก็ไม่พอดีเช่นกัน")
    return (f"รูปนี้คือ{S2.describe(cand)} — ไม่มีตำแหน่งใดที่วางชิ้นที่ 1 ลงได้พอดีเลย "
            "รูปนี้จึงประกอบจากสองชิ้นนี้ไม่ได้")


def assembly_item(a, b, target, rotate, stem, steps, hints, explain, **kw):
    a, b, target = S2.normalize(a), S2.normalize(b), S2.normalize(target)
    assert forms(target, a, b, rotate), "คำตอบประกอบไม่ได้"
    # เขียนขั้นสุดท้ายและเฉลยจากวิธีวางจริง เพื่อไม่ให้ข้อความขัดกับรูปที่โค้ดเลือกมา
    pa = placement(target, a, b, rotate)
    pb = target - pa
    steps = list(steps) + [(f"ตรวจด้วยการวางจริง: ชิ้นที่ 1 ลงที่ {where(pa)}", f"ช่องที่เหลือคือ {where(pb)} ซึ่งเป็นรูปของชิ้นที่ 2 พอดี")]
    explain = (explain + " ตรวจได้จากการวางจริง: ชิ้นที่ 1 ลงที่ " + where(pa)
               + " แล้วช่องที่เหลือเป็นรูปของชิ้นที่ 2 พอดี ส่วนรูปอื่นแม้จะมีจำนวนช่องเท่ากัน "
                 "แต่ไม่ว่าจะวางอย่างไรก็เหลือช่องที่ไม่พอดีเสมอ")
    wrong = decoys(target, a, b, rotate)
    figs = [pieces_fig(a, b)]
    opts = []
    for i, cells in enumerate([target] + wrong):
        figs.append(fig2(f"fig{i + 2}", cells))
        opts.append(f"[[fig{i + 2}]]")
    # เหตุผลของแต่ละตัวลวงคำนวณจากรูปนั้นเอง จะได้ไม่ใช่ข้อความกลาง ๆ เหมือนกันทุกตัว
    return q(stem + "\n\n[[fig1]]", opts[0],
             [(o, why_not_formable(wrong[k], a, b, rotate)) for k, o in enumerate(opts[1:])], steps, hints, explain, figures=figs, **kw)


