def turn(cells, n):
    """หมุนรอบแกนตั้ง ตามเข็มนาฬิกาเมื่อมองจากด้านบน n ครั้ง (ครั้งละ 90 องศา)"""
    for _ in range(n % 4):
        cells = S3.rot_z(cells)
    return cells


def tip(cells, n):
    """ล้มทรงไปทางขวาของภาพ n ครั้ง (ครั้งละ 90 องศา) — หมุนรอบแกนนอน"""
    for _ in range(n % 4):
        cells = S3.rot_y(cells)
    return cells


def fig3(fid, cells, cap=""):
    return {"id": fid, "type": "svg", "svg": S3.iso_svg(cells), "alt": S3.describe(cells), "caption": cap}


def iso_item(shape, answer, wrong, stem, steps, hints, explain, **kw):
    """shape = ทรงต้นแบบ · answer = ทรงหลังหมุนตามที่โจทย์บอก · wrong = [(ทรง, เหตุผล)]"""
    opts = [S3.normalize(answer)] + [S3.normalize(w) for w, _ in wrong]
    assert len(set(opts)) == 5, f"ตัวเลือกซ้ำกันในเชิงพิกัด: {stem}"
    svgs = [S3.iso_svg(o) for o in opts]
    assert len(set(svgs)) == 5, f"ตัวเลือกวาดออกมาเป็นภาพเดียวกัน: {stem}"
    assert all(len(o) == len(shape) for o in opts), f"จำนวนลูกบาศก์ไม่เท่ากัน: {stem}"
    figs = [fig3("fig1", shape, "ทรงต้นแบบ")]
    labels = []
    for i, o in enumerate(opts):
        figs.append(fig3(f"fig{i + 2}", o))
        labels.append(f"[[fig{i + 2}]]")
    return q(stem + "\n\n[[fig1]]", labels[0], [(labels[i + 1], r) for i, (_, r) in enumerate(wrong)],
             steps, hints, explain, figures=figs, **kw)


