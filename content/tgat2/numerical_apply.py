def quant(stem, ans, steps, hints, explain, diff=2, sec=45, tags=None, custom=None, reading="low"):
    reasons = {i: (custom or {}).get(i, QR[i]) for i in range(5) if i != ans}
    return qf(stem, QC, ans, reasons, steps, hints, explain, diff=diff, sec=sec, tags=tags, reading=reading)


def qstem(a, b, cond=""):
    return (f"{cond}\n\n" if cond else "") + f"**(ก)** {a}\n\n**(ข)** {b}\n\nข้อใดถูกต้อง"


