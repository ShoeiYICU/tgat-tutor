def odd_one(stem, panels, ans_idx, attr, steps, hints, explain, **kw):
    """ตรวจว่ามีคุณลักษณะเดียว (attr) ที่แยกภาพ ans_idx ออกจากอีกสี่ภาพ"""
    ks = [key(p) for p in panels]
    assert len(set(ks)) == 5
    names = ["shape", "n", "fill", "arrow", "dot"]
    for i, a in enumerate(names):
        vals = [k[i] for k in ks]
        others = [v for j, v in enumerate(vals) if j != ans_idx]
        splits = len(set(others)) == 1 and vals[ans_idx] != others[0]
        assert splits == (a == attr), f"คุณลักษณะ {a} แยกภาพได้ไม่ตรงที่ตั้งใจ: {stem}"
        for j in range(5):   # ภาพอื่นต้องแยกด้วยคุณลักษณะนี้ไม่ได้
            if j != ans_idx and a != attr:
                rest = [v for t, v in enumerate(vals) if t != j]
                assert not (len(set(rest)) == 1 and vals[j] != rest[0]), f"ภาพที่ {j + 1} ก็แยกได้ด้วย {a}"
    figs, opts = [], []
    for i, p in enumerate(panels):
        figs.append(fig(f"fig{i + 1}", one_svg(p), describe(p)))
        opts.append(f"[[fig{i + 1}]]")
    # เขียนเหตุผลให้เจาะจงรายภาพ โดยบรรยายภาพนั้นก่อน แล้วบอกว่าคุณลักษณะที่ใช้แยกตรงกับภาพอื่น
    wrong = [(opts[j], f"ภาพนี้คือ{describe(panels[j])} · {explain_attr(attr)}ตรงกับภาพอื่น จึงไม่ใช่ภาพที่ต่างจากพวก")
             for j in range(5) if j != ans_idx]
    return q(stem, opts[ans_idx], wrong, steps, hints, explain, figures=figs, **kw)


