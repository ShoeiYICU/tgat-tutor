def P(shape="circle", n=0, fill="solid", arrow=None, dot=None):
    return {"shape": shape, "n": n, "fill": fill, "arrow": arrow, "dot": dot}


def key(p):
    return (p["shape"], p["n"], p["fill"], p["arrow"] % 360 if p["arrow"] is not None else None, p["dot"])


def _shape(kind, cx, cy, s, fill):
    f = 'fill="currentColor"' if fill == "solid" else 'fill="none"'
    st = 'stroke="currentColor" stroke-width="2"'
    if kind == "circle":
        return f'<circle cx="{cx}" cy="{cy}" r="{s / 2}" {f} {st}/>'
    if kind == "square":
        return f'<rect x="{cx - s / 2}" y="{cy - s / 2}" width="{s}" height="{s}" {f} {st}/>'
    return f'<polygon points="{cx},{cy - s / 2} {cx + s / 2},{cy + s / 2} {cx - s / 2},{cy + s / 2}" {f} {st}/>'


def panel(p, x0=0):
    out = [f'<rect x="{x0 + 1}" y="1" width="{S - 2}" height="{S - 2}" rx="6" fill="none" stroke="currentColor" stroke-width="1.5" opacity="0.5"/>']
    if p["n"]:
        pos = GRID6[:p["n"]] if p["n"] > 1 else [(32, 33)]
        out += [_shape(p["shape"], x0 + x, y, 12 if p["n"] > 1 else 20, p["fill"]) for x, y in pos]
    if p["arrow"] is not None:
        cx, cy = x0 + 32, 32
        out.append(f'<g transform="rotate({p["arrow"] % 360} {cx} {cy})" stroke="currentColor" stroke-width="3" fill="currentColor">'
                   f'<line x1="{cx}" y1="{cy + 15}" x2="{cx}" y2="{cy - 8}"/>'
                   f'<polygon points="{cx},{cy - 17} {cx + 7},{cy - 6} {cx - 7},{cy - 6}" stroke-width="1"/></g>')
    if p["dot"] is not None:
        dx, dy = [(10, 10), (54, 10), (54, 54), (10, 54)][p["dot"]]
        out.append(f'<circle cx="{x0 + dx}" cy="{dy}" r="4.5" fill="currentColor"/>')
    return "".join(out)


def describe(p):
    parts = []
    if p["n"]:
        parts.append(f'{SHAPE_TH[p["shape"]]}{"ทึบ" if p["fill"] == "solid" else "โปร่ง"} {p["n"]} รูป')
    if p["arrow"] is not None:
        parts.append(f'ลูกศร{DIR[p["arrow"] % 360]}')
    if p["dot"] is not None:
        parts.append(f'จุดที่{CORNER[p["dot"]]}')
    return " · ".join(parts)


def one_svg(p):
    return f'<svg viewBox="0 0 {S} {S}" xmlns="http://www.w3.org/2000/svg" role="img">{panel(p)}</svg>'


def strip_svg(items):
    """items = spec หรือข้อความ เช่น "?" "→" "::" """
    xs, body, x = [], [], 0
    for it in items:
        if isinstance(it, dict):
            body.append(panel(it, x))
            x += S + GAP
        else:
            w = S if it == "?" else 30
            if it == "?":
                body.append(f'<rect x="{x + 1}" y="1" width="{S - 2}" height="{S - 2}" rx="6" fill="none" stroke="currentColor" stroke-width="1.5" stroke-dasharray="4 3"/>')
            body.append(f'<text x="{x + w / 2}" y="{S / 2 + 8}" font-size="{24 if it == "?" else 20}" text-anchor="middle" fill="currentColor">{it}</text>')
            x += w + GAP
    return f'<svg viewBox="0 0 {x - GAP} {S}" xmlns="http://www.w3.org/2000/svg" role="img">{"".join(body)}</svg>'


def strip_alt(items):
    return " | ".join(describe(i) if isinstance(i, dict) else ("ช่องที่ต้องหา" if i == "?" else i) for i in items)


def fig(fid, svg, alt, cap=""):
    return {"id": fid, "type": "svg", "svg": svg, "alt": alt, "caption": cap}


def visual_q(stem, strip, answer, wrong, steps, hints, explain, **kw):
    """wrong = [(spec, เหตุผล)] · ตรวจว่าตัวเลือกทั้งห้าไม่ซ้ำกัน"""
    keys = [key(answer)] + [key(w) for w, _ in wrong]
    assert len(set(keys)) == len(keys), f"ตัวเลือกซ้ำ: {stem}"
    figs = [fig("fig1", strip_svg(strip), strip_alt(strip), "โจทย์")]
    opts = []
    for i, p in enumerate([answer] + [w for w, _ in wrong]):
        fid = f"fig{i + 2}"
        figs.append(fig(fid, one_svg(p), describe(p)))
        opts.append(f"[[{fid}]]")
    return q(stem + "\n\n[[fig1]]", opts[0], [(opts[i + 1], r) for i, (_, r) in enumerate(wrong)],
             steps, hints, explain, figures=figs, **kw)


def series(frames, **kw):
    """frames = ภาพ 5 ภาพตามกฎ ภาพสุดท้ายเป็นคำตอบ"""
    return visual_q("ภาพใดควรเป็นภาพถัดไปของอนุกรมนี้", frames[:4] + ["?"], frames[4], **kw)


def lesson_fig(items, cap):
    return [fig("fig1", strip_svg(items), strip_alt(items), cap)]


