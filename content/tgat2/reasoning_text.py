def all_orders(names, rules):
    """คืนทุกลำดับ (tuple จากซ้ายไปขวา/ก่อนไปหลัง) ที่ผ่านทุกกฎ"""
    return [p for p in permutations(names) if all(r({n: i for i, n in enumerate(p)}) for r in rules)]


def must(solutions, claim):
    return all(claim(s) for s in solutions)


def can(solutions, claim):
    return any(claim(s) for s in solutions)


def verify(solutions, answer, wrongs, mode="must"):
    """mode must: answer จริงทุกคำตอบ และตัวลวงไม่จริงในทุกคำตอบ (ใช้กับคำถาม 'ข้อใดถูกต้องแน่นอน')
    mode cannot: answer เป็นไปไม่ได้ และตัวลวงเป็นไปได้"""
    assert solutions, "ปริศนาไม่มีคำตอบเลย"
    if mode == "must":
        assert must(solutions, answer), "คำตอบไม่ได้จริงในทุกกรณี"
        for i, w in enumerate(wrongs):
            assert not must(solutions, w), f"ตัวลวงที่ {i + 1} ก็จริงในทุกกรณี"
    elif mode == "cannot":
        assert not can(solutions, answer), "คำตอบเป็นไปได้ในบางกรณี"
        for i, w in enumerate(wrongs):
            assert can(solutions, w), f"ตัวลวงที่ {i + 1} ก็เป็นไปไม่ได้"
    elif mode == "can":
        assert can(solutions, answer), "คำตอบเป็นไปไม่ได้"
        for i, w in enumerate(wrongs):
            assert not can(solutions, w), f"ตัวลวงที่ {i + 1} ก็เป็นไปได้"


