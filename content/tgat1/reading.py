def Q(stem, ans, wrong, steps, hints, explain, diff=2, sec=60, tags=None, reading="medium"):
    return q(stem, ans, wrong, steps, hints, explain, diff=diff, sec=sec, tags=tags, reading=reading)


def N(stem, ans, wrong, clue, explain, diff, tags=None):
    return Q(stem, ans, wrong,
             [("ระบุสิ่งที่โจทย์ถาม", clue), ("ตรวจด้วยบริบทรอบจุดสำคัญ", "เลือกคำตอบที่มีหลักฐานรองรับครบ ไม่เติมข้อมูลเอง")],
             ["ขีดเส้นคำหรือประโยคที่เป็นหลักฐาน", "ตัดตัวเลือกที่จริงบางส่วนแต่ตอบคนละคำถาม", "ตรวจว่าคำตอบไม่กว้างหรือแคบเกินข้อความ"],
             explain, diff=diff, sec=55 if diff == 3 else 75, tags=tags,
             reading="medium" if diff == 3 else "high")


def passage(title, text, question):
    return f"**{title}**\n\n{text}\n\n---\n\n{question}"


